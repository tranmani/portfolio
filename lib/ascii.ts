/**
 * Translates a given string into a multiline ASCII art block.
 * Uses a manual mapping for stability across client and server.
 * Supports A-Z, 0-9, and space.
 */
export const generateAscii = (text: string): string => {
  const chars = text.toUpperCase().split('');
  const lines = ["", "", "", "", "", "", ""];
  
  chars.forEach(char => {
    // If char not in map, just skip it or add placeholder
    const art = ASCII_MAP[char];
    if (art) {
      art.forEach((line, i) => {
        lines[i] += line;
      });
    }
  });
  
  // Clean up empty lines at the end if any
  return lines.filter(line => line.trim().length > 0 || line.length > 0).join('\n');
};
